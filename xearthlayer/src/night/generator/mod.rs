    /// The decoded red of the first texel of each level of a BC1 chain.
    fn level_reds(payload: &[u8], top: u32) -> Vec<u8> {
        let (mut at, mut size, mut reds) = (0, top, Vec::new());
        while size >= 1 {
            let mut rgba = [0u8; 4 * 4 * 4];
            bcdec_rs::bc1(&payload[at..at + 8], &mut rgba, 16);
            reds.push(rgba[0]);
            at += layout::level_len(size, size, DdsFormat::BC1);
            size /= 2;
        }
        reds
    }

    #[test]
    fn the_two_fade_levels_are_dimmed_and_the_rest_are_full() {
        let img = RgbaImage::from_pixel(64, 64, image::Rgba([240, 240, 240, 255]));
        let reds = level_reds(&encode_visible(img).unwrap(), 64);
        assert_eq!(reds.len(), 7, "64 px down to 1 px");
        let near = |got: u8, want: f32| (f32::from(got) - want).abs() <= 8.0;
        assert!(near(reds[0], 240.0 * FADE_RAMP[0]), "nearest {reds:?}");
        assert!(near(reds[1], 240.0 * FADE_RAMP[1]), "second {reds:?}");
        assert!(
            reds[2..].iter().all(|&r| near(r, 240.0)),
            "full below {reds:?}"
        );
    }

    /// The decoded RGB of the first texel of each level of a BC1 chain, or
    /// of as many levels as `payload` holds.
    fn level_rgbs(payload: &[u8], top: u32) -> Vec<[u8; 3]> {
        let (mut at, mut size, mut rgbs) = (0, top, Vec::new());
        while size >= 1 && at < payload.len() {
            let mut rgba = [0u8; 4 * 4 * 4];
            bcdec_rs::bc1(&payload[at..at + 8], &mut rgba, 16);
            rgbs.push([rgba[0], rgba[1], rgba[2]]);
            at += layout::level_len(size, size, DdsFormat::BC1);
            size /= 2;
        }
        rgbs
    }

    fn solid(size: u32, rgb: [u8; 3]) -> RgbaImage {
        RgbaImage::from_pixel(size, size, image::Rgba([rgb[0], rgb[1], rgb[2], 255]))
    }

