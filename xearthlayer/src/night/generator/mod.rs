/// The recipe of the 1 degree tile whose south-west corner is `(lat, lon)`.
pub type RecipeLookup<'a> = &'a (dyn Fn(i32, i32) -> Option<Arc<Recipe>> + Sync);

/// The LED region of the 1 degree tile whose south-west corner is `(lat, lon)`.
pub type RegionLookup<'a> = &'a (dyn Fn(i32, i32) -> LedRegion + Sync);

/// The lit pattern a recipe palette name stands for, or `None` (dark).
pub type PatternLookup<'a> = &'a (dyn Fn(&str) -> Option<Arc<LitPattern>> + Sync);

/// Everything one generation needs.
pub struct LitRequest<'a> {
    /// The lit texture's name: its footprint and zoom.
    pub name: &'a DdsFilename,
    /// Width and height of the first visible level, in pixels.
    pub size: u32,
    /// `night.brightness`.
    pub brightness: f64,
    pub recipes: RecipeLookup<'a>,
    pub patterns: PatternLookup<'a>,
    /// The region each tile's recipe came from.
    pub regions: RegionLookup<'a>,
    /// The LED model; `LedModel::OFF` for sodium only.
    pub led: &'a LedModel,
}

/// Produces the first visible level of a lit texture.
pub trait LitGenerator: Send + Sync {
    /// `size` x `size` pixels, north up, black wherever nothing is lit.
    fn generate(&self, request: &LitRequest<'_>) -> RgbaImage;
}

/// Bump whenever generated bytes change for the same inputs (ramp, tiling,
/// encoder, layout of the visible levels): disk entries of older versions
/// then miss and are regenerated.
///
/// 2: LED patches (`led`).
/// 3: raised LED shares and toned sodium (`led::SodiumTone`, #363).
/// 4: mips averaged in linear light (`lit_chain`, #363).
/// 5: cooler LED whites and halved region shifts (#363).
pub const LIT_GENERATOR_VERSION: u32 = 5;

/// Gamma of the sRGB decode X-Plane applies to a texture's stored values.
pub const SRGB_GAMMA: f32 = 2.2;

/// Scale of the stored values of the first visible levels, nearest first;
/// every level after them is full. X-Plane pages a lit texture's levels in
/// one at a time as the aircraft closes, so without a ramp a texture jumps
/// from full light to the blank level in one step. One step at 2/3 of the
/// light, `(2/3) ^ (1/2.2)` in stored value, softens that without moving the
/// cut-out. Two steps (2/3, 1/3) pushed it a whole level farther out, and
/// stored-value scaling (1/3 read as 9% of the light) read as black before
/// the 3D lights were drawn (both flown 2026-10-18).
pub const FADE_RAMP: [f32; 1] = [0.8318];

/// BC1-encode the first visible level and its mip chain down to 1 x 1, as
/// the bytes that follow the blank levels in a lit DDS (no header). The
/// chain is downsampled from the undimmed image, then the levels named by
/// [`FADE_RAMP`] are dimmed, so the levels below them stay at full light.
pub fn encode_visible(image: RgbaImage) -> Result<bytes::Bytes, crate::dds::DdsError> {
    let mut chain = lit_chain(&image);
    for (level, &gain) in chain.iter_mut().zip(FADE_RAMP.iter()) {
        for px in level.pixels_mut() {
            for c in &mut px.0[..3] {
                *c = (f32::from(*c) * gain).round() as u8;
            }
        }
    }
    let dds =
        crate::dds::DdsEncoder::new(crate::dds::DdsFormat::BC1).encode_with_mipmaps(&chain)?;
    Ok(bytes::Bytes::from(dds).slice(DDS_HEADER_LEN..))
}

/// The mip chain of a lit level down to 1 x 1, averaged in linear light.
/// Lit art is bright points on black, and averaging stored (sRGB) values
/// counts a lit texel beside dark ones at a fraction of its light: by the
/// sixth level a town kept a quarter of its light, and blue, the sparsest
/// channel of warm light, lost the most, so distance made every town dimmer
/// and more orange (#363). Each level is averaged from the linear values of
/// the level above, never from its rounded bytes. Alpha is linear already.
fn lit_chain(image: &RgbaImage) -> Vec<RgbaImage> {
    let decode: [f32; 256] = std::array::from_fn(|v| (v as f32 / 255.0).powf(SRGB_GAMMA));
    let encode = |c: f32| (c.clamp(0.0, 1.0).powf(1.0 / SRGB_GAMMA) * 255.0).round() as u8;
    let (mut w, mut h) = image.dimensions();
    let mut linear: Vec<[f32; 4]> = image
        .pixels()
        .map(|p| {
            let [r, g, b, a] = p.0;
            [
                decode[usize::from(r)],
                decode[usize::from(g)],
                decode[usize::from(b)],
                f32::from(a) / 255.0,
            ]
        })
        .collect();
    let mut chain = vec![image.clone()];
    while w > 1 && h > 1 {
        let (nw, nh) = (w / 2, h / 2);
        let above = &linear;
        let at = |x: u32, y: u32| above[(y * w + x) as usize];
        let next: Vec<[f32; 4]> = (0..nh)
            .flat_map(|y| (0..nw).map(move |x| (x * 2, y * 2)))
            .map(|(x, y)| {
                let q = [at(x, y), at(x + 1, y), at(x, y + 1), at(x + 1, y + 1)];
                std::array::from_fn(|c| (q[0][c] + q[1][c] + q[2][c] + q[3][c]) / 4.0)
            })
            .collect();
        (linear, w, h) = (next, nw, nh);
        chain.push(RgbaImage::from_fn(w, h, |x, y| {
            let [r, g, b, a] = linear[(y * w + x) as usize];
            image::Rgba([encode(r), encode(g), encode(b), (a * 255.0).round() as u8])
        }));
    }
    chain
}

/// Bytes of a DDS header (magic plus the 124-byte header).
const DDS_HEADER_LEN: usize = 128;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::fuse::TextureKind;
    use crate::night::parse_recipe;

    const URBAN: &[u8] = include_bytes!("../../../tests/fixtures/night/urban.oxn");

    #[test]
    fn cooler_led_whites_are_generator_version_five() {
        assert_eq!(LIT_GENERATOR_VERSION, 5);
    }

    fn name_at(lat: f64, lon: f64) -> DdsFilename {
        let n = f64::from(1u32 << 16);
        let x = ((lon + 180.0) / 360.0 * n) as u32;
        let lat_r = lat.to_radians();
        let y = ((1.0 - (lat_r.tan() + 1.0 / lat_r.cos()).ln() / std::f64::consts::PI) / 2.0 * n)
            as u32;
        DdsFilename {
            row: y / 16 * 16,
            col: x / 16 * 16,
            zoom: 16,
            map_type: "BI".into(),
            kind: TextureKind::Lit,
        }
    }

    fn generate(name: &DdsFilename, size: u32) -> RgbaImage {
        let recipes = |lat: i32, lon: i32| {
            ((lat, lon) == (37, -123)).then(|| Arc::new(parse_recipe(URBAN).unwrap()))
        };
        let patterns = |n: &str| {
            (n == "lib/g10/terrain10/urban_tmp_sdry3.ter").then(|| {
                Arc::new(LitPattern {
                    size: 4,
                    rgb: vec![[255, 0, 0]; 16],
                    ground_scale_m: 4096.0,
                })
            })
        };
        CpuLitGenerator.generate(&LitRequest {
            name,
            size,
            brightness: 1.0,
            recipes: &recipes,
            patterns: &patterns,
            regions: &|_, _| LedRegion::Unknown,
            led: &LedModel::OFF,
        })
    }

    #[test]
    fn encoded_visible_levels_fit_the_layout() {
        let layout = crate::night::LitLayout::new(18, 4); // first visible 256
        let img = generate(&name_at(37.20, -122.725), 256);
        let payload = encode_visible(img).unwrap();
        assert_eq!(payload.len() as u64, layout.payload_len());
        assert!(payload.iter().any(|&b| b != 0), "light survives encoding");
    }

    /// The decoded red of the first texel of each level of a BC1 chain.
    fn level_reds(payload: &[u8], top: u32) -> Vec<u8> {
        let (mut at, mut size, mut reds) = (0, top, Vec::new());
        while size >= 1 {
            let mut rgba = [0u8; 4 * 4 * 4];
            bcdec_rs::bc1(&payload[at..at + 8], &mut rgba, 16);
            reds.push(rgba[0]);
            at += (size.div_ceil(4) * size.div_ceil(4) * 8) as usize;
            size /= 2;
        }
        reds
    }

    #[test]
    fn the_first_visible_level_is_dimmed_and_the_rest_are_full() {
        let img = RgbaImage::from_pixel(64, 64, image::Rgba([240, 240, 240, 255]));
        let reds = level_reds(&encode_visible(img).unwrap(), 64);
        assert_eq!(reds.len(), 7, "64 px down to 1 px");
        let near = |got: u8, want: f32| (f32::from(got) - want).abs() <= 8.0;
        assert!(
            near(reds[0], 240.0 * FADE_RAMP[0]),
            "first visible {reds:?}"
        );
        assert!(
            reds[1..].iter().all(|&r| near(r, 240.0)),
            "full below {reds:?}"
        );
    }

    /// A one-texel checkerboard of `lit` and black.
    fn checker(size: u32, lit: [u8; 3]) -> RgbaImage {
        RgbaImage::from_fn(size, size, |x, y| {
            let [r, g, b] = if (x + y) % 2 == 0 { lit } else { [0; 3] };
            image::Rgba([r, g, b, 255])
        })
    }

    fn light(v: u8) -> f32 {
        (f32::from(v) / 255.0).powf(SRGB_GAMMA)
    }

    #[test]
    fn mip_levels_keep_the_light_of_the_level_above() {
        // Half the texels sodium, half black: every smaller level gives half
        // the light in each channel, so it is neither dimmer nor warmer.
        let lit = [200, 120, 50];
        let source = checker(64, lit);
        let chain = lit_chain(&source);
        assert_eq!(chain.len(), 7, "64 px down to 1 px");
        assert_eq!(chain[0], source, "the first level is the image");
        for (level, img) in chain.iter().enumerate().skip(1) {
            let p = img.get_pixel(0, 0);
            for c in 0..3 {
                let (got, want) = (light(p[c]), light(lit[c]) / 2.0);
                assert!(
                    (got - want).abs() <= want * 0.05,
                    "level {level} channel {c}: {got} against {want}"
                );
            }
        }
    }

    #[test]
    fn encoded_mips_average_light_not_stored_values() {
        // Half of 240's light is stored 175; averaging stored values gives 120.
        let reds = level_reds(&encode_visible(checker(64, [240; 3])).unwrap(), 64);
        assert!(
            reds[1..].iter().all(|&r| (i32::from(r) - 175).abs() <= 8),
            "{reds:?}"
        );
    }

    #[test]
    fn the_dimmed_level_gives_two_thirds_of_the_light() {
        // Stored values are sRGB: the light they give is value ^ 2.2.
        let light = FADE_RAMP.map(|v| v.powf(SRGB_GAMMA));
        assert_eq!(light.len(), 1);
        assert!((light[0] - 2.0 / 3.0).abs() < 1e-3, "{light:?}");
    }
}
